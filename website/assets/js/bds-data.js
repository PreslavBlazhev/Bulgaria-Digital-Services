  /** „от 250 €“ — само ако има одобрена цена. */
  function priceFromLabel(pkg) {
    if (typeof pkg.priceFrom !== 'number') return null;
    return 'от ' + pkg.priceFrom + ' ' + META.currency;
  }

  /** Цената, както е записана в източника: точна стойност или диапазон.
      Диапазон се показва само ако наистина има горна граница. */
  function priceLabel(pkg) {
    if (typeof pkg.priceFrom !== 'number') return null;
    if (typeof pkg.priceTo === 'number') {
      return 'от ' + pkg.priceFrom + ' до ' + pkg.priceTo + ' ' + META.currency;
    }
    return pkg.priceFrom + ' ' + META.currency;
  }

